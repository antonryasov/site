# ---------------------------------------------------------------- рендер для сайта

def _esc(t):
    return (t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))


def paragraphs(text):
    """"""
    parts = [p.strip() for p in text.split('\n\n') if p.strip()]
    return parts


def read_time(text):
    minutes = max(1, int(round(len(text) / 900.0)))
    return '%s · %d мин чтения' % ('текст поста', minutes)


def render_cards():
    """Вертикальная редакционная лента из пяти постов."""
    out = []
    for p in POSTS:
        body = []
        for i, para in enumerate(paragraphs(p['text'])):
            if i == len(paragraphs(p['text'])) - 1 and para.startswith('#'):
                body.append('<p class="tgp-tags">%s</p>' % _esc(para))
            elif para.startswith('#'):
                body.append('<p class="tgp-tags">%s</p>' % _esc(para))
            else:
                body.append('<p>%s</p>' % _esc(para).replace('\n', '<br/>'))
        out.append(
            '<article class="tgp-post" id="tg-%d">'
            '<div class="tgp-post-head"><span class="tgp-tag">%s</span><span class="tgp-num">пост %02d</span></div>'
            '<h2 class="tgp-post-title">%s</h2>'
            '<div class="tgp-post-body">%s</div>'
            '<div class="tgp-post-foot"><span class="tgp-date">%s</span>'
            '<a class="text-link" href="https://t.me/nu_takoe_ot_antona" target="_blank" rel="noopener">'
            'Открыть канал <span>↗</span></a></div>'
            '</article>' % (p['n'], _esc(p['tag']), p['n'], _esc(p['title']), ''.join(body), read_time(p['text']))
        )
    return ''.join(out)


