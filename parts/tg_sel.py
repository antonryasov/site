    data = {'channel': '@nu_takoe_ot_antona',
            'note': 'Очередь публикации: status = готов / опубликован / черновик / снят',
            'posts': []}
    if os.path.isfile(path):
        try:
            data = json.load(io.open(path, encoding='utf-8'))
        except Exception:
            pass
    by_id = {p['id']: p for p in data.get('posts', [])}
    out = []
    for p in POSTS:
        pid = '%02d' % p['n']
        old = by_id.get(pid, {})
        out.append({
            'id': pid,
            'tag': p['tag'],
            'title': p['title'],
            'text': p['text'],
            'status': old.get('status', 'готов'),
            'publish_after': old.get('publish_after'),
            'published_at': old.get('published_at'),
            'message_id': old.get('message_id'),
        })
    data['posts'] = out
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2))
        f.write('\n')
    return path


