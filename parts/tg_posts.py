# ---------------------------------------------------------------- генерация

FIRST_COUNT = len(FIRST)


def series_dates():
    return [SERIES_START + datetime.timedelta(days=i) for i in range(len(SERIES))]


def post_id(n):
    return '%02d' % n


def publish_after(d):
    return '%sT%s+03:00' % (d.isoformat(), SERIES_TIME_MSK)


def all_posts():
    """55 записей: первые пять (без publish_after) + серия 50 (с датами).

    id 01–05 — первые пять, id 06–55 — серия, по порядку дат.
    """
    out = []
    for i, p in enumerate(FIRST, 1):
        out.append({
            'id': post_id(i),
            'tag': p['tag'],
            'title': p['title'],
            'text': p['text'],
            'publish_after': None,
            'note': 'первые пять — сразу после подключения бота',
        })
    for i, (p, d) in enumerate(zip(SERIES, series_dates()), 1):
        out.append({
            'id': post_id(FIRST_COUNT + i),
            'tag': p['tag'],
            'title': p['title'],
            'text': p['text'],
            'publish_after': publish_after(d),
            'note': 'серия 1 пост в день, %d из %d' % (i, len(SERIES)),
        })
    return out


def to_queue(path):
    """Очередь для бота. Статусы, message_id и даты публикации уже вышедших постов не трогаем."""
    data = {
        'channel': '@nu_takoe_ot_antona',
        'note': 'status: готов / опубликован / черновик / снят. publish_after — не раньше этой даты (МСК).',
        'series_start': SERIES_START.isoformat(),
        'series_time_msk': SERIES_TIME_MSK,
        'series_len': len(SERIES),
        'posts': [],
    }
    old = {}
    if os.path.isfile(path):
        try:
            prev = json.load(io.open(path, encoding='utf-8'))
            old = {p.get('id'): p for p in prev.get('posts', [])}
            if prev.get('channel'):
                data['channel'] = prev['channel']
        except Exception:
            old = {}
    out = []
    for p in all_posts():
        before = old.get(p['id'], {})
        status = before.get('status') or 'готов'
        item = {
            'id': p['id'],
            'tag': p['tag'],
            'title': p['title'],
            'text': p['text'],
            'status': status,
            'publish_after': p['publish_after'],
            'published_at': before.get('published_at'),
            'message_id': before.get('message_id'),
            'note': p['note'],
        }
        out.append(item)
    data['posts'] = out
    tmp = path + '.tmp'
    with io.open(tmp, 'w', encoding='utf-8') as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2))
        f.write('\n')
    os.replace(tmp, path)
    return path


